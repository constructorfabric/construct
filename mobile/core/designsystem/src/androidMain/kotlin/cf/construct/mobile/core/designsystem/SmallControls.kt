package cf.construct.mobile.core.designsystem

import androidx.compose.ui.unit.dp

/** The sizes of the small icons and actions that the notices, the lists and the buttons of every page share. */
object SmallControls {
    /** An icon in a notice or a row, and the spinner that takes its place. */
    val icon = 16.dp

    /** The least height of a text action under a notice, and of a small button. */
    val action = 44.dp

    /** The line of a small spinner, such as the one in a button or a row. */
    val spinnerStroke = 2.dp
}
